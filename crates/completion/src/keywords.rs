pub fn keyword_groups_for(engine: Engine) -> [&'static [&'static str]; 3] {
    let engine_keywords = match engine {
        Engine::Postgres => PG_KEYWORDS,
        Engine::SqlServer => MSSQL_KEYWORDS,
        Engine::Sqlite => &[
            "PRAGMA",
            "REPLACE",
            "RETURNING",
            "STRICT",
            "WITHOUT ROWID",
            "EXPLAIN QUERY PLAN",
        ],
    };
    [STATEMENT_LEADS, COMMON_KEYWORDS, engine_keywords]
}

